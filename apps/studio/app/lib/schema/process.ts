import type { Entry } from "@animelist/packages-schema";
import type { SetOptional } from "type-fest";
import type { FlatEntry, SourceType } from "@/lib/schema/types";
import { ulid } from "ulidx";

const ID_PREFIX = "@autogenerated_";
const AUTO_ID_REGEX = new RegExp(`^${ID_PREFIX}.+$`);

export function flattenEntries(
    entries: Entry[],
    options?: { style?: boolean; parentId?: string; source?: SourceType },
) {
    const flatten: FlatEntry[] = [];

    for (const entry of entries) {
        const hasId = Boolean(entry.id);
        const id = entry.id ?? `${ID_PREFIX}${ulid()}`;

        const { children, related, ...rest } = entry;
        const flated: FlatEntry = {
            ...rest,
            id,
        };

        if (options?.parentId) {
            flated._parentId = options.parentId;
        }

        if (options?.source) {
            flated._source = options.source;
        }

        if (!hasId) {
            flated._isGeneratedId = true;
        }

        if (!flated._parentId && options?.style) {
            flated.style = getGradient([flated.id]);
        }

        flatten.push(flated);

        if (children && children.length > 0) {
            flatten.push(
                ...flattenEntries(children, {
                    ...options,
                    parentId: id,
                    source: "children",
                }),
            );
        }

        if (related && related.length > 0) {
            flatten.push(
                ...flattenEntries(related, {
                    ...options,
                    parentId: id,
                    source: "related",
                }),
            );
        }
    }

    return flatten;
}

export function unflattenEntries(
    entriesMap: Map<FlatEntry["id"], FlatEntry>,
): Entry[] {
    const map = new Map<
        string,
        SetOptional<FlatEntry, "id"> & {
            children?: Entry[];
            related?: Entry[];
            _source?: SourceType;
        }
    >();
    const roots: Entry[] = [];

    for (const [id, entry] of entriesMap) {
        map.set(id, { ...entry, children: [], related: [] });
    }

    for (const [id, entry] of entriesMap) {
        const current = map.get(id);
        if (!current) {
            continue;
        }

        if (current?.id && AUTO_ID_REGEX.test(current.id)) {
            delete current.id;
        }

        const source = current._source;

        delete current._parentId;
        delete current._isGeneratedId;
        delete current.style;
        delete current._source;

        if (!entry._parentId) {
            roots.push(current);
            continue;
        }

        const parent = map.get(entry._parentId);
        if (!parent) {
            roots.push(current);
            continue;
        }

        if (source === "related") {
            parent.related = parent.related || [];
            parent.related.push(current);
            continue;
        }

        parent.children = parent.children || [];
        parent.children.push(current);
    }

    for (const item of map.values()) {
        if (item.children && !item.children.length) {
            delete item.children;
        }

        if (item.related && !item.related.length) {
            delete item.related;
        }
    }

    return roots;
}
